import { schemas } from '../src/lib/admin-schema.mjs';
import { writeFile } from 'node:fs/promises';
const quote = (v) => JSON.stringify(v);
function conditions(key, f) {
  const v = `d.${key}`;
  if (f.type === 'number') return `${v} is int && ${v} >= 0 && ${v} <= 9999`;
  const rules = [
    `${v} is string`,
    `${v}.size() <= ${f.type === 'image' ? 900000 : f.type === 'textarea' ? 5000 : 1000}`,
  ];
  if (f.required) rules.push(`${v}.size() > 0`);
  if (f.choices) rules.push(`${v} in ${JSON.stringify(f.choices)}`);
  let pattern;
  if (f.type === 'time') pattern = '([01][0-9]|2[0-3]):[0-5][0-9]';
  if (f.type === 'date') pattern = '[0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01])';
  if (f.type === 'datetime-local')
    pattern = '[0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01])T([01][0-9]|2[0-3]):[0-5][0-9]';
  if (f.type === 'url') pattern = 'https://[^/@ :]+([/?#][^ ]*)?';
  if (f.type === 'media')
    pattern = 'https://(www[.])?(youtube[.]com|youtu[.]be|vimeo[.]com|soundcloud[.]com)/[^ ]+';
  if (f.type === 'image') pattern = 'data:image/jpeg;base64,[A-Za-z0-9+/=]+';
  if (f.type === 'asset') pattern = '/assets/[A-Za-z0-9_./-]+';
  if (pattern) rules.push(`(${v} == '' || ${v}.matches(${quote(pattern)}))`);
  return rules.join(' && ');
}
const validators = Object.entries(schemas)
  .map(
    ([kind, schema]) => `function valid_${kind}(d) {
  return d.keys().hasAll(${JSON.stringify(Object.keys(schema))}) && d.keys().hasOnly(${JSON.stringify(Object.keys(schema))})
  && ${Object.entries(schema)
    .map(([key, f]) => conditions(key, f))
    .join(
      '\n  && ',
    )}${kind === 'prayer' ? '\n  && d.effectiveTo >= d.effectiveFrom' : kind === 'events' ? '\n  && d.end > d.start' : ''};
}`,
  )
  .join('\n');
await writeFile(
  'firestore.rules',
  `// Generated by scripts/generate-admin-rules.mjs. Deploy before the new admin client.
rules_version = '2';
service cloud.firestore {
match /databases/{database}/documents {
 function board() { return request.auth != null && request.auth.token.email_verified == true && request.auth.token.email in ['msaatuic@gmail.com','zhaid3@uic.edu']; }
 function finance() { return board() && request.auth.token.get('msaRole','') in ['admin','treasurer']; }
 function permitted(kind) { return kind in ['donations','giving'] ? finance() : board(); }
 ${validators}
 function validRecord(r,key) {
   return r.keys().hasOnly(['kind','id','data','revision','schemaVersion','archived','updatedAt','publishedAt','updatedBy'])
   && r.keys().hasAll(['kind','id','data','revision','schemaVersion','archived','updatedAt','publishedAt','updatedBy'])
   && r.kind in ${JSON.stringify(Object.keys(schemas))}
   && r.id is string && r.id.size() <= 100 && r.id.matches('[a-z0-9]+(-[a-z0-9]+)*')
   && key == r.kind + '--' + r.id
   && (r.kind != 'prayer' || r.id == 'current') && (r.kind != 'giving' || r.id == 'campaign')
   && r.schemaVersion == 1 && r.revision is int && r.revision >= 0 && r.archived is bool
   && r.updatedBy == request.auth.token.email && r.updatedAt is timestamp && r.updatedAt == request.time
   && (r.publishedAt == null || r.publishedAt is timestamp) && r.data is map
   && (${Object.keys(schemas)
     .map((k) => `(r.kind == '${k}' && valid_${k}(r.data))`)
     .join(' || ')});
 }
 function baseRevision(key) { return exists(/databases/$(database)/documents/cmsPublic/$(key)) ? get(/databases/$(database)/documents/cmsPublic/$(key)).data.revision : 0; }
 match /cmsPublic/{key} {
   allow read: if true;
   allow create, update: if permitted(request.resource.data.kind) && validRecord(request.resource.data,key)
     && request.resource.data.revision == baseRevision(key) + 1
     && request.resource.data.publishedAt == request.resource.data.updatedAt
     && getAfter(/databases/$(database)/documents/cmsHistory/$(key + '--' + string(request.resource.data.revision))).data == request.resource.data;
   allow delete: if false;
 }
 match /cmsDrafts/{key} {
   allow read: if board();
   allow create, update: if board() && validRecord(request.resource.data,key) && request.resource.data.revision == baseRevision(key);
   allow delete: if board() && permitted(resource.data.kind);
 }
 match /cmsHistory/{key} {
   allow read: if board();
   allow create: if permitted(request.resource.data.kind)
     && validRecord(request.resource.data,request.resource.data.kind + '--' + request.resource.data.id)
     && key == request.resource.data.kind + '--' + request.resource.data.id + '--' + string(request.resource.data.revision)
     && getAfter(/databases/$(database)/documents/cmsPublic/$(request.resource.data.kind + '--' + request.resource.data.id)).data == request.resource.data;
   allow update, delete: if false;
 }
 // Existing documents stay readable; edits now live in cmsPublic and override by slug.
 match /events/{eventId} { allow read: if true; allow write: if false; }
 match /{document=**} { allow read, write: if false; }
}
}
`,
);
